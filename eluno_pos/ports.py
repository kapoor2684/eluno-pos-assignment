"""Ports: what the core needs from the outside world. Shopify, the store tool and the terminal are adapters behind these."""
from dataclasses import dataclass
from typing import List, Optional, Protocol
from .domain import Customer, Product, Rx, PlacedOrder, PlacedRefund

@dataclass(frozen=True)
class Location:
    ref: int; store_code: str; kind: str; invoice_prefix: Optional[str]

class Commerce(Protocol):              # system of record (Shopify today)
    def locations(self) -> List[Location]: ...
    def find_customer(self, phone: str) -> Optional[Customer]: ...
    def catalog(self) -> List[Product]: ...
    def stock(self, products: List[Product], location_ref: int) -> dict: ...
    def create_order(self, draft: dict) -> PlacedOrder: ...          # idempotent on draft['bill_key']
    def get_order(self, ref: int) -> PlacedOrder: ...
    def find_order_by_invoice(self, invoice_no: str, location_ref: int) -> Optional[PlacedOrder]: ...
    def orders(self, location_ref: int, since_days: int) -> List[PlacedOrder]: ...
    def existing_invoice_numbers(self, location_ref: int) -> List[str]: ...
    def refund_order(self, order: PlacedOrder, req: dict) -> PlacedRefund: ...   # idempotent on req['refund_key']

class Prescriptions(Protocol):         # store tool
    def prescriptions(self, phone: str) -> List[Rx]: ...
    def staff(self, store_code: str) -> List[dict]: ...

class Terminal(Protocol):
    def charge(self, amount_paise: int, method: str, order_ref: str) -> str: ...      # idempotent on order_ref
    def refund(self, charge_id: str, amount_paise: int, reason: str) -> str: ...
    def refunded_paise(self, charge_id: str) -> int: ...    # used to detect a refund that succeeded but whose response was lost
